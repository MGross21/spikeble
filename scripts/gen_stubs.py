"""Generate SPIKE MicroPython stub packages from LEGO's official docs.

Usage:
    python scripts/gen_stubs.py                # fetch upstream, write stubs/
    python scripts/gen_stubs.py --source FILE  # use a local documents.json
    python scripts/gen_stubs.py --check        # exit 1 if stubs/ is stale
"""

import argparse
import gzip
import json
import re
import shutil
import sys
import urllib.request
from pathlib import Path
from typing import Any

Page = dict[str, Any]

URL = "https://spike.legoeducation.com/content/documents.json"
LOCALE = "en-us"
ROOT = "lls-help-python-spm"
OUT = Path(__file__).resolve().parent.parent / "stubs"
DESCRIPTION = (
    "Generate SPIKE MicroPython stub packages from LEGO's official docs."
)
HEADER = f"# Generated by scripts/gen_stubs.py from {URL}; do not edit."

NORMALIZE = str.maketrans({" ": " ", "‘": "'", "’": "'"})
MATH = re.compile(r"\$([^$]+)\$")
RETURN_PREFIX = re.compile(r"^\w+\s+(?=\w+\()")
BRACKETS = re.compile(r"\[([^\[\]]*)\]")
FIELD_NAME = re.compile(r"\b\w+:\s*")
CONST = re.compile(r"\$\*\*(\w+)\*\*\$\s*=\s*(-?\d+)")


def load(source: Path | None) -> Page:
    if source:
        return json.loads(source.read_bytes())
    req = urllib.request.Request(
        URL,
        headers={"User-Agent": "spikeble-gen-stubs", "Accept-Encoding": "gzip"},
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        data = resp.read()
        if resp.headers.get("Content-Encoding") == "gzip":
            data = gzip.decompress(data)
    return json.loads(data)


def kids(page: Page) -> list[Page]:
    return page.get("sub_pages") or []


def content(page: Page) -> list[Page]:
    return page.get("content") or []


def find(page: Page, title: str) -> Page | None:
    if page.get("title") == title:
        return page
    return next((hit for sub in kids(page) if (hit := find(sub, title))), None)


def inline(text: str) -> str:
    return MATH.sub(r"`\1`", text.translate(NORMALIZE))


def clean_lines(text: str) -> list[str]:
    return [line.strip() for line in inline(text).strip().splitlines()]


def texts(page: Page) -> list[str]:
    return [c["text"]["content"] for c in content(page) if "text" in c]


def code_block(stack: Page) -> list[str]:
    code = stack["code"].translate(NORMALIZE)
    for i, comment in enumerate(stack.get("comments") or [], 1):
        code = code.replace(f"{{Comment {i}}}", comment["comment"].strip())
    lines = [line.rstrip() for line in code.strip().splitlines()]
    return ["```python", *lines, "```"]


def render(items: list[Page], heading: list[str]) -> list[str]:
    out: list[str] = []
    for item in items:
        if "text" in item:
            out += clean_lines(item["text"]["content"])
        stacks = item.get("python_code_stacks") or {}
        for stack in stacks.get("python_code_stack", []):
            out += ["", *heading, *code_block(stack)]
    return out


def fix_signature(sig: str, module: str) -> str:
    sig = RETURN_PREFIX.sub("", inline(sig).strip().strip("`").strip())
    sig = BRACKETS.sub(lambda m: f"[{FIELD_NAME.sub('', m[1])}]", sig)
    return re.sub(rf"\b{module}\.(?=[A-Z_]+\b)", "", sig)


def docstring(lines: list[str], indent: str) -> list[str]:
    body = "\n".join(lines).strip("\n")
    if not body:
        return []
    body = body.replace("\\", "\\\\").replace('"""', r"\"\"\"")
    return [
        f'{indent}"""',
        *(f"{indent}{line}" if line else "" for line in body.splitlines()),
        f'{indent}"""',
    ]


def function(page: Page, module: str) -> list[str]:
    first, *rest = content(page)
    sig = fix_signature(first["text"]["content"], module)
    lines = render(rest, ["Example", "-------"])
    params: list[str] = []
    for sub in kids(page):
        title = sub["title"]
        if "section-header" in title or title.endswith("optional-star"):
            continue
        params.append(
            inline(sub["page_title"]).strip("`").replace(": ", " : ", 1)
        )
        params += [
            f"    {line}" if line else ""
            for t in texts(sub)
            for line in clean_lines(t)
        ]
    if params:
        lines += ["", "Parameters", "----------", *params]
    return [f"def {sig}:", *docstring(lines, "    "), "    ..."]


def constants(page: Page) -> list[str]:
    out: list[str] = []
    for t in texts(page):
        for line in t.translate(NORMALIZE).splitlines():
            line = line.strip()
            if m := CONST.fullmatch(line):
                out.append(f"{m[1]}: Final = {m[2]}")
            elif line and out:
                out.append(f'"""{inline(line)}"""')
    return out


def module_source(page: Page, name: str) -> str:
    leaf = name.rpartition(".")[2]
    prefix = f"{page['title']}-"
    body: list[str] = []
    consts: list[str] = []

    def collect(node: Page) -> None:
        for sub in kids(node):
            title = sub["title"]
            if title.startswith(f"{prefix}func-"):
                body.extend(["", "", *function(sub, leaf)])
            elif title == f"{prefix}consts":
                consts.extend(constants(sub))
            elif "section-header" in title:
                collect(sub)

    collect(page)
    src = "\n".join(body + consts)
    imports = []
    if leaf != "motor" and re.search(r"\bmotor\.", src):
        imports.append("import motor")
    typing = {
        n for n in ("Awaitable", "Callable") if re.search(rf"\b{n}\b", src)
    }
    if consts:
        typing.add("Final")
    if typing:
        imports.append(f"from typing import {', '.join(sorted(typing))}")

    parts = [HEADER, *docstring(render(content(page), []), "")]
    if imports:
        parts += ["", *imports]
    if consts:
        parts += ["", *consts]
    return "\n".join(parts + body) + "\n"


def generate(docs: Page) -> dict[Path, str]:
    spm = find(docs[LOCALE], ROOT)
    if spm is None:
        sys.exit(f"{ROOT} not found in {LOCALE} documents")
    files: dict[Path, str] = {}
    for mod in kids(spm):
        name = mod["title"].removeprefix(f"{ROOT}-")
        pkg = Path(f"{name}-stubs")
        files[pkg / "__init__.pyi"] = module_source(mod, name)
        sub_page = re.compile(re.escape(mod["title"]) + r"-(\w+)")
        for sub in kids(mod):
            if (m := sub_page.fullmatch(sub["title"])) and m[1] != "consts":
                files[pkg / f"{m[1]}.pyi"] = module_source(
                    sub, f"{name}.{m[1]}"
                )
    return files


def stale(files: dict[Path, str]) -> list[Path]:
    on_disk = {p.relative_to(OUT) for p in OUT.rglob("*.pyi")}
    return sorted(
        rel
        for rel in on_disk | files.keys()
        if rel not in on_disk
        or rel not in files
        or (OUT / rel).read_bytes() != files[rel].encode()
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=DESCRIPTION)
    parser.add_argument(
        "--source", type=Path, help="local documents.json instead of fetching"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if stubs/ differs from upstream",
    )
    args = parser.parse_args()
    files = generate(load(args.source))

    if args.check:
        if changed := stale(files):
            print("Stubs out of date:", *changed, sep="\n  ")
            sys.exit(1)
        print("Stubs up to date.")
        return

    shutil.rmtree(OUT, ignore_errors=True)
    for rel, src in files.items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(src.encode())
    print(f"Wrote {len(files)} files to {OUT}")


if __name__ == "__main__":
    main()
